export function getParentProfile(id: string): ParentProfile {
  if (id === "4" || id === "sherif-gamal") {
    return mockSherifProfile
  }
  if (id === "1" || id === "hana-mostafa") {
    return mockHanaProfile
  }

  // Find parent in mockParents or fallback
  const found = mockParents.find((p) => p.id === id)
  if (!found) {
    return mockHanaProfile
  }

  return {
    ...mockHanaProfile,
    id: found.id,
    code: `PAR-2051${found.id}`,
    name: found.name,
    avatarUrl: found.avatarUrl,
    avatarInitials: found.avatarInitials,
    avatarColorClass: found.avatarColorClass,
    status: found.status,
    email: found.email,
    phone: found.phone,
    registeredDate: found.registeredDate,
    kpis: {
      linkedChildren: found.childrenCount,
      activeSubscriptions: found.activeSubscriptions,
      pointsBalance: found.childrenCount * 600 + 40,
      pendingRequests: found.activeSubscriptions > 0 ? 1 : 0,
    },
  }
}
